#!/usr/bin/env bash
# Compose the spec into Claude Code artifacts under plugin/.
#
# Claude Code agent and skill files are flat single files with no include
# mechanism, so the prompt stack (shared fragments + role prompt + memory index)
# must be concatenated at build time. Edit the spec, never plugin/ — everything
# under plugin/agents and plugin/skills is generated and overwritten.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$(pwd)

STACK=(
  shared/charter.md
  shared/communication-protocol.md
  shared/resource-discipline.md
  shared/lifecycle.md
  shared/escalation.md
  shared/definition-of-done.md
  shared/memory-protocol.md
)

# Strip YAML frontmatter (everything through the second '---').
body() { awk 'BEGIN{n=0} /^---$/ && n<2 {n++; next} n>=2 {print}' "$1"; }

adaptation() {
  cat <<'EOF'

---

# Running inside Claude Code

This spec assumes a mesh where agents message each other directly. Claude Code
spawns you from a session and reads what you return, so adapt as follows:

- **The session is the Manager.** Everything the spec routes to the Manager —
  `HANDOFF`, `BLOCKED`, `PROGRESS`, `SCOPE_CHANGE`, `CONFLICT`, `BUDGET` — goes
  into what you return. Use the message formats verbatim; they are what the
  Manager parses.
- **Direct messaging when available.** If you have `ListAgents`/`SendMessage` and
  the agent you need is listed, message it directly as the protocol says.
  Otherwise put the question in your return with `OWNER:` naming who should
  answer, and the Manager will route it.
- **Budgets are self-enforced.** Nothing stops you at the ceiling. Count your own
  tool calls and commands, warn at 70%, and stop at 100% with a specific
  extension request rather than continuing.
- **Stuck is self-reported.** No supervisor is watching your progress. When a
  trigger fires, return `SELF_STUCK` with a complete `RULED_OUT` — that brief is
  the only thing that survives you.
- **You must not spawn agents.** You have no spawn authority under this spec, and
  the session is the Manager. If you need work done that is not yours, put it in
  your return — as `SCOPE_CHANGE`, `BLOCKED`, or a named follow-up — and let the
  Manager decide. This holds even when you can see exactly what a helper would do.
- **Your final text is the return value,** not a message to a human. No preamble,
  no summary. Emit the artifact the spec calls for.
EOF
}

# Model tier per role, read from team.yaml's `model:` field so the spec stays the
# source of truth. Capability is a budget: spend it where a wrong answer is
# expensive, not where the work is voluminous.
role_model() {
  awk -v role="$1" '
    $0 == "  " role ":" { inrole=1; next }
    inrole && /^    model:/ { print $2; exit }
    inrole && /^  [a-z-]+:$/ { exit }
  ' team.yaml
}

gen_agent() {
  local role="$1"
  local name="$2"
  local desc="$3"
  local out="plugin/agents/${name}.md"
  local model
  model=$(role_model "$role")
  [ -n "$model" ] || { echo "no model: for role $role in team.yaml" >&2; exit 1; }
  {
    printf -- '---\nname: %s\ndescription: %s\nmodel: %s\n---\n\n' "$name" "$desc" "$model"
    printf '<!-- GENERATED by bin/build.sh from roles/%s.md — do not edit. -->\n' "$role"
    for f in "${STACK[@]}"; do printf '\n'; cat "$f"; done
    printf '\n---\n\n'
    body "roles/${role}.md"
    printf '\n---\n\n# Team memory (snapshot at build time)\n\n'
    sed '/^<!--/,/-->/d' memories/_index.md
    printf '\nFull entries: %s/memories/. Rebuild after any memory change.\n' "$ROOT"
    adaptation
  } > "$out"
  printf '  %-28s %-7s %5s lines\n' "$name" "$model" "$(wc -l < "$out" | tr -d ' ')"
}

echo "Generating agents:"
gen_agent product-manager team-product-manager \
  "The team's single Product Manager. Use for any product question: what should this do, is it in scope, what are the acceptance criteria, what is the priority, should this be descoped. Answers with a decision, never a survey. Does not decide implementation."
gen_agent architect team-architect \
  "The team's single Architect. Use for any technical question: which boundary, which pattern, is this debt acceptable, is this feasible and what does it cost, what interface should parallel work build against. Rules decisively and records ADRs. Does not decide what gets built."
gen_agent dev-engineer team-dev-engineer \
  "Implements one tightly scoped task (at most 3 files, at most 5 acceptance criteria) inside a stated budget. Spawn one per independent task with disjoint write paths. Returns a HANDOFF with assumptions, risks, and spend. Never reviews or verifies its own work."
gen_agent qe-engineer team-qe-engineer \
  "Independently verifies a change against its acceptance criteria by executing tests, and writes test plans and defect reports. Spawn for verification after review. Must not be the agent that authored the change. May fail a task; may not mark it done."
gen_agent code-reviewer team-code-reviewer \
  "Reviews a change for correctness, safety, contract fidelity, and test adequacy before it reaches QE. Every blocking finding carries a concrete failure scenario. Spawn one per change; must not be the agent that authored it. Describes fixes, never writes them."

echo "Generating skill:"
{
  cat <<'EOF'
---
name: agent-team
description: Run a task through the multi-agent delivery team — decompose it into tightly scoped tasks, spawn dev/QE/reviewer agents, route product questions to the Product Manager and technical questions to the Architect, enforce budgets, and gate on the Definition of Done. Use when the user wants a piece of work delivered by the agent team rather than done inline.
allowed-tools: Read, Glob, Grep, Bash, Write, Edit, Agent, AskUserQuestion, TodoWrite
---
EOF
  printf '\n<!-- GENERATED by bin/build.sh from roles/manager.md — do not edit. -->\n'
  cat <<EOF

# Agent Team

You are the **Manager** of the delivery team for this task. You are the singleton
that holds authority; the other roles are spawned as subagents:

| Need | Spawn |
|---|---|
| A product decision | \`team-product-manager\` |
| A technical ruling | \`team-architect\` |
| Implementation of one scoped task | \`team-dev-engineer\` |
| Independent verification | \`team-qe-engineer\` |
| The quality gate before QE | \`team-code-reviewer\` |

**Run this session on opus** (\`/model opus\`). You are the Manager, and your
decomposition and conflict rulings are the highest-leverage output on the team —
a bad split costs more than every agent it spawns. The subagents carry their own
tiers: \`team-product-manager\`, \`team-architect\`, and \`team-code-reviewer\` run
on opus because their output binds other agents; \`team-dev-engineer\` and
\`team-qe-engineer\` run on sonnet because their work is high-volume and tightly
scoped. Raise a single agent with the Agent tool's \`model\` override when one
task warrants it, and say why — never as a blanket default.

**You are the only agent that spawns.** No subagent you create may spawn another;
their prompts forbid it. If one returns work it wants done, you scope it and
decide.

**Singletons are spawned once and reused for the whole goal.** Spawn
\`team-product-manager\` and \`team-architect\` at most once each, then reach them
again with SendMessage for every later question. A second Agent call for either
role creates a second source of product or technical truth and is a protocol
violation — if you have lost the handle, use ListAgents to find it rather than
spawning again.

**Pooled roles are spawned per task, many at once.** A fresh \`team-dev-engineer\`,
\`team-qe-engineer\`, or \`team-code-reviewer\` per task, up to the pool caps
(8/4/4), retired when the task lands and never reused for unrelated work.

Enforce yourself what the orchestrator would enforce: never route a change to a
reviewer or QE agent that authored it, never give two concurrent tasks the same
write path (repo-qualified, workspace-wide), never assign a consumer task before
its producer task is DONE, and never spawn a fourth agent at the same scope after
two respawns.

Spec: ${ROOT}
EOF
  for f in "${STACK[@]}"; do printf '\n'; cat "$f"; done
  printf '\n---\n\n'
  body roles/manager.md
  printf '\n---\n\n# Team memory (snapshot at build time)\n\n'
  sed '/^<!--/,/-->/d' memories/_index.md
} > plugin/skills/agent-team/SKILL.md
printf '  %-28s %5s lines\n' agent-team "$(wc -l < plugin/skills/agent-team/SKILL.md | tr -d ' ')"

echo "Done. Install locally with bin/install-local.sh"
